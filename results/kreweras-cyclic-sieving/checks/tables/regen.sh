#!/bin/sh
# Regenerate data/krew_tables.json from the arXiv v2 LaTeX source of Reiner and Sommers and compare it
# byte for byte with the file the checkers read. Needs network access; optional, not run by check.sh.
set -eu
here=$(CDPATH= cd -- "$(dirname -- "$0")" && pwd)
py=${PYTHON:-python3}
work=$(mktemp -d)
trap 'rm -rf "$work"' EXIT HUP INT TERM
curl -fsSL --retry 3 -o "$work/src.gz" https://arxiv.org/e-print/1605.09172v2
gunzip -c "$work/src.gz" > "$work/main.tex"
echo "a81380408c49d9abf74c308bcc3e1174f5e3e93c75befb577c216dc2b6699e8f  $work/main.tex" | sha256sum -c --quiet
"$py" -I "$here/extract.py" "$work/main.tex" > "$work/raw.json"
"$py" -I "$here/convert.py" "$work/raw.json" > "$work/krew_tables.json"
cmp "$work/krew_tables.json" "$here/../../data/krew_tables.json"
echo "PASS: data/krew_tables.json regenerated byte for byte from the arXiv v2 source"
