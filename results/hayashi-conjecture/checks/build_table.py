#!/usr/bin/env python3
"""Checker B, part 1 (numpy; imports nothing from
the other checkers): build the operation table of the quandle from a certificate.

Elements are affine maps w -> T w + v of B = sum of F_p^d blocks, stored as
one integer row per map (per block: T row-major, then v).  The class C of
c0 = P o (w -> w + g0) under conjugation by the generators of G (the
translations by basis vectors, a1, a2, and their inverses) is found by
breadth-first search; then T[x, y] = index of y x y^-1 for all x, y in C.
An entry outside C is a rejection (C not closed under *).  The table is
written as n*n little-endian uint16, row x, column y, so column y is the
right translation R_y; check_table.c then checks every quandle axiom on it.

usage: build_table.py qprime.json OUT.bin
"""
import hashlib, json, resource, sys, time
import numpy as np

t0 = time.process_time()
cert = json.load(open(sys.argv[1]))
PR, DIM = cert["primes"], cert["dims"]
OFF = []
o = 0
for d in DIM:
    OFF.append(o); o += d * d + d
WIDTH = o


def blocks(X):
    """Yield (p, d, T, v) views for a batch X of shape (n, WIDTH)."""
    for p, d, off in zip(PR, DIM, OFF):
        T = X[:, off:off + d * d].reshape(-1, d, d)
        v = X[:, off + d * d:off + d * d + d]
        yield p, d, T, v


def pack(parts, n):
    X = np.empty((n, WIDTH), np.int64)
    for (T, v), d, off in zip(parts, DIM, OFF):
        X[:, off:off + d * d] = T.reshape(n, d * d)
        X[:, off + d * d:off + d * d + d] = v
    return X


def compose(X, Y):
    """Rows of X o Y (apply Y first), batched; X or Y may have one row."""
    n = max(len(X), len(Y))
    parts = []
    for (p, d, T1, v1), (_, _, T2, v2) in zip(blocks(X), blocks(Y)):
        T = np.einsum("nij,njk->nik", np.broadcast_to(T1, (n, d, d)),
                      np.broadcast_to(T2, (n, d, d))) % p
        v = (np.einsum("nij,nj->ni", np.broadcast_to(T1, (n, d, d)),
                       np.broadcast_to(v2, (n, d))) + v1) % p
        parts.append((T, v))
    return pack(parts, n)


def inverse_one(x):
    """Inverse of a single affine map (row), by brute force over the finite
    group generated by its linear part blocks (exact and simple)."""
    parts = []
    for p, d, T, v in blocks(x[None, :]):
        T = T[0]; M = np.eye(d, dtype=np.int64); Ti = None
        for _ in range(p ** (d * d)):
            if np.array_equal((M @ T) % p, np.eye(d, dtype=np.int64)):
                Ti = M; break
            M = (M @ T) % p
        assert Ti is not None, "singular block"
        parts.append((Ti[None], (-(Ti @ v[0]) % p)[None]))
    return pack(parts, 1)[0]


RADIX = []
for p, d in zip(PR, DIM):
    RADIX += [p] * (d * d + d)
RADIX = np.array(RADIX, np.int64)
assert float(np.prod(RADIX.astype(float))) < 2 ** 62
WEIGHT = np.concatenate([[1], np.cumprod(RADIX)[:-1]]).astype(np.int64)


def keys(X):
    return X @ WEIGHT


def element(Ts, vs):
    return pack([(np.array(T, np.int64)[None] % p, np.array(v, np.int64)[None] % p)
                 for T, v, p in zip(Ts, vs, PR)], 1)[0]


zero = [[0] * d for d in DIM]
eye = [np.eye(d, dtype=np.int64).tolist() for d in DIM]
gens = [element(cert["a1"], zero), element(cert["a2"], zero)]
for j, d in enumerate(DIM):
    for b in range(d):
        vs = [list(z) for z in zero]; vs[j][b] = 1
        gens.append(element(eye, vs))
gens += [inverse_one(s) for s in gens]
P = element(cert["P"], zero)
g0 = element(eye, cert["g0"])
c0 = compose(P[None], g0[None])[0]


def conj_all(y, X):
    """y x y^-1 for every row x of X."""
    yi = inverse_one(y)
    return compose(compose(y[None], X), yi[None])


# breadth-first search for the class of c0 under conjugation by G
cls = c0[None].copy(); seen = set(keys(cls).tolist()); front = cls
while len(front):
    new = np.concatenate([conj_all(s, front) for s in gens])
    k = keys(new)
    _, first = np.unique(k, return_index=True)
    new = new[first]; k = k[first]
    mask = np.array([kk not in seen for kk in k.tolist()], bool)
    front = new[mask]; seen.update(k[mask].tolist())
    cls = np.concatenate([cls, front])
    assert len(cls) <= 10 ** 5, "class too large"
order = np.argsort(keys(cls)); cls = cls[order]; ck = keys(cls)
n = len(cls)
Tab = np.empty((n, n), np.uint16)
for j in range(n):
    k = keys(conj_all(cls[j], cls))
    idx = np.searchsorted(ck, k)
    idx[idx >= n] = 0
    if not np.array_equal(ck[idx], k):
        print("REJECT: the class is not closed under *"); sys.exit(1)
    Tab[:, j] = idx
Tab.astype("<u2").tofile(sys.argv[2])
print("|Q'| =", n, "; table sha256", hashlib.sha256(Tab.astype("<u2").tobytes()).hexdigest())
print("CPU %.1f s, peak %d MB" % (time.process_time() - t0,
      resource.getrusage(resource.RUSAGE_SELF).ru_maxrss // 1024))
