"""Replay higher-class-number theta coefficients from the certified graph.

The checker constructs ideal classes from reduced forms, derives the local
offsets from principal powers, and independently enumerates and projects
every ring class in PARI. It pushes graph paths forward to find the terminal
flags. No theta evaluator or class transfer implementation is imported.
"""
import argparse
from collections import Counter
from hashlib import sha256
from itertools import product
import json
from math import gcd, isqrt, prod
from pathlib import Path

from sage.all import EllipticCurve, QuadraticField, ZZ, pari

from brandt import BrandtGraph, same_lattice
from check_theta import (
    IDENTITY, class_number, coordinates, determinant, find_generator, fixed_flags,
    index_of, insist, labelled_rays, load, multiply, preimage, pushed_cover,
    splitting, times, unpack, vector,
)


def reduced_forms(D):
    for a in range(1, isqrt(-D // 3) + 1):
        for b in range(-a, a + 1):
            c, remainder = divmod(b*b - D, 4*a)
            if not remainder and a <= c and (b >= 0 or (-b != a and a != c)):
                yield a, b, c


def coprime_form(form, avoid):
    a, b, c = form

    def value(x, y):
        return a*x*x + b*x*y + c*y*y

    # Bezout completes any primitive column to a proper equivalence.
    # Primitivity and coprimality can be arranged by CRT, so the search ends.
    height = 1
    while True:
        for y in range(height + 1):
            for x in range(-height, height + 1):
                if max(abs(x), y) != height or gcd(x, y) != 1:
                    continue
                A = value(x, y)
                if gcd(A, avoid) != 1:
                    continue
                _, v, u = ZZ(x).xgcd(y)
                z, w = -int(u), int(v)
                B = 2*a*x*z + b*(x*w+y*z) + 2*c*y*w
                return A, B, value(z, w)
        height += 1


def ring_labels(D, p, shift, forms):
    """Check every form class and derive the first cyclic-layer projection."""
    h = len(forms)
    v = int(ZZ(h).valuation(p))
    depth = 2+v
    trace = D % 2
    norm = (trace*trace-D)//4
    F = p**depth
    qfb = pari.Qfb
    identity = qfb(1, F*trace, F*F*norm).qfbred()
    gamma = qfb(shift*shift+shift*trace+norm, F*(2*shift+trace), F*F).qfbred()
    lifts = [qfb(A, F*B, F*F*C).qfbred() for A, B, C in forms]
    local_order = (p+1)*p**(depth-1)
    count = h*local_order
    exponent = (h//p**v)*(p+1)
    insist(int(pari.qfbclassno(D*F*F)) == count, "PARI ring class number")
    powers = [identity]
    for _ in range(1, local_order):
        powers.append(powers[-1].qfbcomp(gamma))
    insist(powers[-1].qfbcomp(gamma) == identity, "PARI ray-generator order")
    image_sizes = [p, 1]
    if v:
        # Compute the sizes of the successive power-map images on the
        # whole group. The last nontrivial image must be cyclic of order p.
        image = {tuple(lift.qfbcomp(g).qfbpow(exponent).Vec())
                 for lift, g in product(lifts, powers)}
        insist(len(image) > 1, "missing p-primary ring classes")
        image_sizes = [len(image)]
        while True:
            smaller = {tuple(qfb(*a).qfbpow(p).Vec()) for a in image}
            image_sizes.append(len(smaller))
            if len(smaller) == 1:
                break
            insist(len(smaller) < len(image), "the p-primary image did not shrink")
            image = smaller
            exponent *= p
        insist(len(image) == p, "longest p-primary cyclic factor is ambiguous")
    pivot = gamma.qfbpow(exponent)
    if pivot == identity:
        pivot = next((a for lift in lifts if (a := lift.qfbpow(exponent)) != identity), None)
        insist(pivot is not None, "missing generator of the projection")
    logs = {tuple(pivot.qfbpow(k).Vec()): k for k in range(p)}
    insist(len(logs) == p and pivot.qfbpow(p) == identity, "PARI projection order")
    step = logs[tuple(gamma.qfbpow(exponent).Vec())]
    # The reduction kernel to conductor p² is generated by this power
    # of gamma because the local group is cyclic of order local_order.
    insist(gamma.qfbpow(p*(p+1)*exponent) == identity,
           "first cyclic layer does not descend to conductor p squared")
    offsets = []
    seen = set()
    for lift in lifts:
        offset = logs[tuple(lift.qfbpow(exponent).Vec())]
        offsets.append(offset)
        for k, power in enumerate(powers):
            element = lift.qfbcomp(power)
            key = tuple(element.Vec())
            insist(key not in seen, "repeated ring class")
            seen.add(key)
            projected = logs[tuple(element.qfbpow(exponent).Vec())]
            insist(projected == (offset+k*step) % p, "independent ring class exponent")
    insist(len(seen) == count, "incomplete ring class enumeration")
    projection = dict(depth=depth, classes=count, power=exponent, image_sizes=image_sizes)
    return step, offsets, projection


def graph_data(case, ell, directory, graph, levels, factors, p_slot):
    p = case["p"]
    payload = load(directory/"classes.json")
    rebuilt = graph.class_data(case["D"])
    for key in ("cm", "units", "ell"):
        insist(payload[key] == rebuilt[key], f"exact {key} replay")
    moduli = [int(level**graph.depths[level]) for level in levels]
    rows = []
    for row in load(directory/f"q{p}.json"):
        edges = []
        for entry in row:
            target = entry["index"]
            maps = unpack(entry, levels, moduli)
            insist(type(target) is int and 0 <= target < len(graph.ideals),
                   "invalid edge target")
            for k, (A, (q, _)) in enumerate(zip(maps, factors)):
                d = determinant(A)
                insist(d % p == 0 and d % (p*p) != 0 if k == p_slot else d % q != 0,
                       "incorrect graph determinant")
            edges.append((target, maps))
        insist(len(edges) == p+1, "wrong graph degree")
        rows.append(edges)
    insist(len(rows) == len(graph.ideals), "wrong graph size")
    return rebuilt, rows, moduli


def unit_action(maps, flag, factors):
    return tuple(index_of(times(A, vector(s, q, m)), q, m)
                 for A, s, (q, m) in zip(maps, flag, factors))


def eigen_samples(directory, factors, units, graph, p):
    values = load(directory/"eigen.json")
    sizes = [m+m//q for q, m in factors]
    strides = [prod(sizes[j:]) for j in range(len(sizes)+1)]
    insist(len(values) == len(graph.ideals)*strides[0] and
           all(type(x) is int and 0 <= x < p for x in values) and
           next((x for x in values if x), 0) == 1, "eigenvector shape or normalization")
    # The complete norm-one list contains both signs except for -1 itself.
    projective = []
    moduli = [m for _, m in factors]
    for records, weight in zip(units, graph.weights):
        matrices = [unpack(r, [q for q, _ in factors],
                           [q**graph.depths[q] for q, _ in factors]) for r in records]
        group = {min(tuple(tuple(v % m for v in A) for A, m in zip(u, moduli)),
                     tuple(tuple(-v % m for v in A) for A, m in zip(u, moduli)))
                 for u in matrices}
        identity = (IDENTITY,)*len(factors)
        insist(len(group)*2 == weight and identity in group, "projective unit group")
        for u, v in product(group, repeat=2):
            uv = tuple(multiply(A, B, m) for A, B, m in zip(u, v, moduli))
            minus = tuple(tuple(-x % m for x in A) for A, m in zip(uv, moduli))
            insist(min(uv, minus) in group, "unit group closure")
        projective.append(group)
    cache = {}

    def sample(vertex, flags):
        key = vertex, flags
        if key not in cache:
            def lookup(f):
                return values[vertex*strides[0] + sum(s*w for s, w in zip(f, strides[1:]))]
            orbit = Counter(unit_action(u, flags, factors) for u in projective[vertex])
            stabilizer = orbit[flags]
            size = len(orbit)
            insist(stabilizer*size == len(projective[vertex]) and
                   set(orbit.values()) == {stabilizer}, "terminal orbit-stabilizer")
            value = lookup(flags)
            insist(all(lookup(f) == value for f in orbit), "terminal eigenvalue on unit orbit")
            for f in orbit:
                cache[vertex, f] = (value, stabilizer)
        return cache[key]

    def census():
        """Count stabilizers even for flags outside the chosen CM rays."""
        hist = Counter()
        for vertex in range(len(graph.ideals)):
            for flags in product(*(range(n) for n in sizes)):
                _, stabilizer = sample(vertex, flags)
                hist[stabilizer] += 1
        return dict(sorted(hist.items()))

    return sample, census


def walk(graph, source, omega, K, root, forms, factors, labels, p_slot, offsets):
    p = factors[p_slot][0]
    D = int(root*root)
    trace = D % 2
    # If alpha = x + y*sqrt(D), its image is x - trace*y + 2*y*omega.
    def embed(alpha):
        x, y = K(alpha).list()
        return (x-trace*y) + 2*y*omega

    old = graph.ideals[source]
    transfers = []
    for (A, B, _), offset in zip(forms, offsets):
        delta = (root-B)/2
        c = K.ideal(A, delta)
        insist(c.norm() == A, "ordinary ideal norm")
        power = c**len(forms)
        alpha, = power.gens_reduced()
        insist(K.ideal(alpha) == power, "uncertified principal power")
        # Conjugation of alpha is congruent to alpha^-1 projectively.
        image = embed(alpha.conjugate())
        projected = graph.local_transport(source, source, image)[p]
        ray = coordinates(tuple(int(x) for x in projected.column(0)), p, p*p)
        insist(ray in labels, "principal inverse did not preserve the ray chart")
        if len(forms) % p:
            insist(labels[ray] % p == len(forms)*offset % p,
                   "principal inverse disagrees with PARI")
        J = graph.order.right_ideal([q*x for q in (A, embed(delta)) for x in old.basis()])
        target, beta = graph.classify(J)
        insist(same_lattice(beta*graph.ideals[target], J) and
               beta.reduced_norm()*graph.ideals[target].norm() == A*old.norm(),
               "ideal equality or reduced norm")
        conjugate = (~beta)*omega*beta
        maps = graph.local_transport(target, source, ~beta)
        flats = tuple(tuple(int(x) for x in maps[q].list()) for q, _ in factors)
        insist(all(determinant(A_q) % q for A_q, (q, _) in zip(flats, factors)),
               "noninvertible coset transport")
        transfers.append((target, str(conjugate), flats, offset))
    return transfers


def rotate(coefficients, shift):
    p = len(coefficients)
    return [coefficients[(j-shift) % p] for j in range(p)]


def moment(coefficients):
    return sum(j*x for j, x in enumerate(coefficients)) % len(coefficients)


def insert_p(flags, p_slot):
    return list(flags[:p_slot]+(None,)+flags[p_slot:])


def unit_rebases(graph, embeddings, variants, factors, p_slot, step):
    """Check exact source unit conjugation and the induced rebasing."""
    p = factors[p_slot][0]
    tame = factors[:p_slot]+factors[p_slot+1:]
    actions = {}
    count = 0
    for (i, name), (omega, _, _, choices) in embeddings.items():
        if i not in actions:
            units = [u for u in graph._order_elements(i, 1)[1] if u != -1]
            actions[i] = [(u, graph.transport(i, i, u, 1)) for u in units]
        seen = set()
        for unit, mats in actions[i]:
            target = str(unit*omega*~unit)
            insist((i, target) in embeddings, "unit conjugation leaves embedding set")
            seen.add(target)
            _, _, logs, _ = embeddings[i, target]
            start = coordinates(tuple(int(x) for x in mats[p].column(0)), p, p*p)
            maps = tuple(tuple(int(x) for x in mats[q].list()) for q, _ in tame)
            for flags in product(*choices):
                moved = unit_action(maps, flags, tame)
                coeff = variants[i, name, flags]["coefficients"]
                insist(variants[i, target, moved]["coefficients"] ==
                       rotate(coeff, step*logs[start]),
                       "source unit rebase")
                count += 1
        insist(2*len(seen) == graph.weights[i], "source CM embedding stabilizer")
    return count


def evaluate(case, ell, directory):
    """Reconstruct the canonical theta array and explicit replay audit."""
    directory = Path(directory)
    p, D, N = (case[key] for key in ("p", "D", "N"))
    h = class_number(D)
    if h <= 1 or p < 5:
        raise NotImplementedError("requires h > 1 and p >= 5")
    factors = [(int(q), int(q**e)) for q, e in ZZ(N).factor()]
    levels = [q for q, _ in factors]
    insist(ZZ(p).is_prime() and ZZ(ell).is_prime() and p in levels and
           levels == case["levels"] and ell not in levels, "invalid level support")
    p_slot = levels.index(p)
    tame = factors[:p_slot]+factors[p_slot+1:]
    insist(factors[p_slot][1] == p and splitting(D, p) == splitting(D, ell) == -1
           and all(splitting(D, q) == 1 for q, _ in tame), "invalid local conditions")
    trace = D % 2
    norm = (trace*trace-D)//4
    shift = find_generator(p, trace, norm)
    forms = [coprime_form(f, N*ell) for f in reduced_forms(D)]
    insist(len(forms) == h, "ordinary class number")
    step, offsets, projection = ring_labels(D, p, shift, forms)

    graph = BrandtGraph.from_case(case, ell)
    classes, rows, moduli = graph_data(case, ell, directory, graph, levels, factors, p_slot)
    roots = list(graph.cm_embeddings(D))
    sample, census = eigen_samples(directory, factors, classes["units"], graph, p)
    embeddings = {}
    for (i, omega), record in zip(roots, classes["cm"], strict=True):
        name = str(omega)
        insist((record["index"], record["omega"]) == (i, name), "embedding order")
        matrices = unpack(record, levels, moduli)
        logs = labelled_rays(matrices[p_slot], shift, p, 2, trace, norm)
        tame_matrices = matrices[:p_slot]+matrices[p_slot+1:]
        choices = [fixed_flags(A, q, m, trace, norm) for A, (q, m) in zip(tame_matrices, tame)]
        embeddings[i, name] = (omega, matrices, logs, choices)
    insist(len(embeddings) == len(roots), "duplicate embedding")
    K = QuadraticField(D, "root")
    root = K.gen()
    ap, vdelta = case["ap"], case["vdelta"]
    insist(abs(ap) == 1 and vdelta > 0, "invalid normalization")
    scale = vdelta*pow(ap, -2, p) % p
    covers = {}
    variants = {}
    relations = []
    for (i, name), (omega, _, logs, choices) in embeddings.items():
        transfers = walk(graph, i, omega, K, root, forms, factors, logs, p_slot, offsets)
        prepared = []
        for target, conjugate, maps, offset in transfers:
            insist((target, conjugate) in embeddings, "missing transferred embedding")
            _, _, target_logs, _ = embeddings[target, conjugate]
            if target not in covers:
                covers[target] = [pushed_cover(rows, target, p, n, factors, p_slot)
                                  for n in (1, 2)]
            small, large = covers[target]
            insist(large.keys() == logs.keys() and len(small) == p+1, "graph ray cover")
            mapping = {coordinates(times(maps[p_slot], ray), p, p*p): (k*step+offset) % p
                       for ray, k in logs.items()}
            start = coordinates(times(maps[p_slot], (1, 0)), p, p*p)
            insist(mapping.keys() == large.keys() and
                   all(mapping[r] == (offset+step*(target_logs[r]-target_logs[start])) % p
                       for r in mapping), "transported ray equivariance")
            rebase = step*target_logs[start]-offset
            prepared.append((target, conjugate, maps, large, mapping, rebase))

        for flags in product(*choices):
            coeff = [0]*p
            labels = Counter()
            stab = Counter()
            for target, conjugate, maps, large, mapping, rebase in prepared:
                tame_maps = maps[:p_slot]+maps[p_slot+1:]
                moved = unit_action(tame_maps, flags, tame)
                relations.append(((i, name, flags), (target, conjugate, moved), rebase))
                small, _ = covers[target]
                sums = Counter()
                counts = Counter()
                for ray, (vertex, slope, path) in large.items():
                    f = tuple(preimage(A, s, q, m) for A, s, (q, m) in zip(path, moved, tame))
                    value, stabilizer = sample(vertex, f[:p_slot]+(slope,)+f[p_slot:])
                    reduced = coordinates(ray, p, p)
                    sums[reduced] += value
                    counts[reduced] += 1
                    coeff[mapping[ray]] += scale*value
                    labels[mapping[ray]] += 1
                    stab[stabilizer] += 1
                insist(counts.keys() == small.keys() and set(counts.values()) == {p},
                       "wrong depth-one fibre size")
                for ray, (vertex, slope, _) in small.items():
                    value, _ = sample(vertex, moved[:p_slot]+(slope,)+moved[p_slot:])
                    insist((sums[ray]-ap*value) % p == 0, "pointwise depth-two norm")
            coeff = [x % p for x in coeff]
            insist(len(labels) == p and set(labels.values()) == {h*(p+1)},
                   "wrong degree-p fibres")
            insist(sum(coeff) % p == 0, "nonzero augmentation")
            T = moment(coeff)
            origins = Counter(k*step % p for k in logs.values())
            origin_count = p if step else 1
            insist(len(origins) == origin_count and
                   set(origins.values()) == {p*(p+1)//origin_count} and
                   all(moment(rotate(coeff, -r)) == T for r in origins), "base ray translations")
            variants[i, name, flags] = dict(index=i, omega=name, tame_flags=insert_p(flags, p_slot),
                                            first_moment=T, coefficients=coeff,
                                            terminal_stabilizers=dict(sorted(stab.items())))

    for source, target, rebase in relations:
        insist(target in variants and variants[target]["coefficients"] ==
               rotate(variants[source]["coefficients"], rebase), "class rebase")

    unit_checks = unit_rebases(graph, embeddings, variants, factors, p_slot, step)
    E = EllipticCurve(case["ainvs"])
    tame_signs = {k: -int(E.ap(q))
                  for k, (q, m) in enumerate(tame) if q == m}
    orientation_checks = 0
    for (i, name, flags), variant in variants.items():
        omega, _, _, choices = embeddings[i, name]
        coeff = variant["coefficients"]
        conjugate = variants[i, str(trace-omega), flags]["coefficients"]
        insist(conjugate == [coeff[-j % p] for j in range(p)], "conjugation inversion")
        flips = []
        for k, (q, _) in enumerate(tame):
            other = next(s for s in choices[k] if s != flags[k])
            flipped = flags[:k]+(other,)+flags[k+1:]
            actual = variants[i, name, flipped]["coefficients"]
            signs = [tame_signs[k]] if k in tame_signs else [1, -1]
            matches = []
            for sign in signs:
                expectation = [sign*c % p for c in coeff]
                matches.extend((sign, s) for s in range(p) if rotate(expectation, s) == actual)
            insist(matches, "tame orientation sign and translation")
            flips.append(dict(prime=q, sign_and_shift=matches))
            orientation_checks += 1
        variant["tame_flips"] = flips

    ordered = [value for _, value in sorted(variants.items(), key=lambda item:
               (item[0][1], item[0][0], item[0][2]))]
    selected = ordered[0]
    insist(len({min(v["first_moment"], p-v["first_moment"]) for v in ordered}) == 1,
           "CM choices have inconsistent moment magnitudes")
    return dict(first_moment=selected["first_moment"], coefficients=selected["coefficients"],
                checks=dict(class_number=h, ring_classes=h*p*(p+1), forms=forms, offsets=offsets,
                            generator_shift=shift, local_step=step, base_rays=p*(p+1),
                            projection=projection,
                            exponent_fibre=h*(p+1),
                            class_rebases=len(relations), unit_rebases=unit_checks,
                            orientation_checks=orientation_checks,
                            all_flag_stabilizers=census(),
                            weights=list(map(int, graph.weights)), variants=ordered))


def compare_variants(produced, replay, D, p):
    """Identify the two additive coordinates, then compare each oriented sum."""
    from sage.all import BinaryQF
    checks = replay["checks"]
    independent = {(v["index"], v["omega"], tuple(v["tame_flags"])): v["coefficients"]
                   for v in checks["variants"]}
    def classes(forms, offsets):
        result = {}
        for form, offset in zip(forms, offsets, strict=True):
            f = BinaryQF(list(form))
            insist(f.discriminant() == D, "coset discriminant")
            result[tuple(f.reduced_form())] = offset
        return result

    compared = set()
    for v in produced["checks"]["variants"]:
        key = v["index"], v["omega"], tuple(v["tame_flags"])
        insist(key in independent and key not in compared, "oriented CM variant")
        compared.add(key)
        if v["local_step"]:
            scale = checks["local_step"] * pow(v["local_step"], -1, p) % p
        else:
            # The degree-p character descends to the ordinary class group.
            # A different first nonzero ordinary class can normalize its basis.
            insist(checks["local_step"] == 0, "local reciprocity character")
            a = classes(v["forms"], v["offsets"])
            b = classes(checks["forms"], checks["offsets"])
            insist(a.keys() == b.keys() and len(a) == checks["class_number"], "ideal class cover")
            c = next(c for c in a if a[c])
            scale = b[c] * pow(a[c], -1, p) % p
            insist(all((scale*a[c]-b[c]) % p == 0 for c in a), "global class offsets")
        insist(scale and all(x == independent[key][j*scale % p]
                             for j, x in enumerate(v["coefficients"])),
               "independent ideal-class coefficients")
    insist(compared == independent.keys(), "missing oriented CM variant")


def check(case, ell, directory, trial):
    """Check the exact frozen trial coefficients, moment, status, and eigen digest."""
    directory = Path(directory)
    result = evaluate(case, ell, directory)
    insist(trial["ell"] == ell, "wrong trial ell")
    insist(trial["coefficients"] == result["coefficients"], "frozen coefficients")
    insist(trial["T"] == result["first_moment"], "frozen first moment")
    insist(trial["status"] == ("nonzero" if result["first_moment"] else "zero"),
           "frozen status")
    raw = json.dumps(load(directory/"eigen.json"), sort_keys=True, separators=(",", ":"))
    insist(sha256(raw.encode()).hexdigest() == trial["eigen_sha256"], "frozen eigen digest")
    return result


if __name__ == "__main__":
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("case", type=Path)
    parser.add_argument("ell", type=int)
    parser.add_argument("directory", type=Path)
    parser.add_argument("--trial", type=Path)
    args = parser.parse_args()
    case = load(args.case)
    result = (check(case, args.ell, args.directory, load(args.trial)) if args.trial
              else evaluate(case, args.ell, args.directory))
    print(json.dumps(result, sort_keys=True))
