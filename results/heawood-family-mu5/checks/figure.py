"""Draw G1 and G2 (data/graphs.g6) as TikZ for the paper's Figure 1, or check it.

Usage: figure.py data/graphs.g6              print the TikZ picture
       figure.py --check data/graphs.g6 paper/paper.tex

The left drawing is G1 with the edge {1,10} dashed (deleting it gives H) and
the triangle {1,5,10} drawn thick. The right drawing is G2: G1 after the
Delta-Y transformation on that triangle, with the new vertex outside the
circle next to the triangle, every vertex labeled by its number in G2 (an isomorphism from the
transformed graph to G2 is computed here). With --check, the picture between
the markers in paper.tex is parsed and must have exactly the edge sets of G1
and G2, the dashed edge {1,10}, the thick triangle {1,5,10} in G1, and in G2
three thick edges at the degree-3 vertex 7, whose replacement by a triangle gives
G1 back.
"""
import math, random, re, sys
import networkx as nx
from networkx.algorithms.isomorphism import GraphMatcher

BEGIN = "% BEGIN Figure 1, generated by checks/figure.py from data/graphs.g6"
END = "% END Figure 1"
DASHED = (1, 10)
TRIANGLE = (1, 5, 10)
NEW = 7  # the vertex of G2 that the Delta-Y transformation creates


def graphs(path):
    g6 = dict(l.split() for l in open(path))
    return nx.from_graph6_bytes(g6["G1"].encode()), nx.from_graph6_bytes(g6["G2"].encode())


def crossings(G, order):
    pos = {v: i for i, v in enumerate(order)}
    E = [tuple(sorted((pos[a], pos[b]))) for a, b in G.edges()]
    return sum(1 for (a, b) in E for (c, d) in E if a < c < b < d)


def circle_order(G):
    rng = random.Random(1619)
    best = list(sorted(G)); cost = crossings(G, best)
    for _ in range(20000):
        i, j = rng.sample(range(len(best)), 2)
        cand = best[:]; cand[i], cand[j] = cand[j], cand[i]
        c = crossings(G, cand)
        if c <= cost:
            best, cost = cand, c
    return best


def delta_y(G, tri, y):
    X = G.copy()
    X.remove_edges_from([(a, b) for a in tri for b in tri if a < b])
    X.add_edges_from((y, a) for a in tri)
    return X


def picture(G1, G2):
    order = circle_order(G1)
    r = 2.0
    pos = {v: (r * math.cos(math.pi / 2 - 2 * math.pi * k / len(order)),
               r * math.sin(math.pi / 2 - 2 * math.pi * k / len(order))) for k, v in enumerate(order)}
    y = max(G1) + 1
    cx, cy = (sum(pos[a][t] for a in TRIANGLE) for t in (0, 1))
    pos[y] = (1.4 * r * cx / math.hypot(cx, cy), 1.4 * r * cy / math.hypot(cx, cy))
    X = delta_y(G1, TRIANGLE, y)
    phi = next(GraphMatcher(X, G2).isomorphisms_iter())
    tri_edges = {frozenset((a, b)) for a in TRIANGLE for b in TRIANGLE if a < b}
    out = [BEGIN, r"\begin{tikzpicture}[scale=0.9,v/.style={circle,draw,fill=white,inner sep=1pt,minimum size=13pt,font=\scriptsize}]"]
    for side, shift, G, P, lab in (("a", 0.0, G1, pos, {v: v for v in G1}),
                                   ("b", 6.0, G2, {phi[v]: pos[v] for v in X}, {phi[v]: phi[v] for v in X})):
        for v in sorted(G):
            x, yy = P[v]
            out.append(r"\node[v] (%s%d) at (%.2f,%.2f) {%d};" % (side, v, x + shift, yy, lab[v]))
        for u, v in sorted(tuple(sorted(e)) for e in G.edges()):
            if side == "a" and (u, v) == DASHED:
                style = "dashed,very thick"
            elif side == "a" and frozenset((u, v)) in tri_edges:
                style = "very thick"
            elif side == "b" and phi[y] in (u, v):
                style = "very thick"
            else:
                style = "gray"
            out.append(r"\draw[%s] (%s%d) -- (%s%d);" % (style, side, u, side, v))
    out.append(r"\node at (0,-3.3) {$G_1$};")
    out.append(r"\node at (6,-3.3) {$G_2$};")
    out.append(r"\end{tikzpicture}")
    out.append(END)
    return "\n".join(out)


def check(G1, G2, tex):
    text = open(tex).read()
    if text.count(BEGIN) != 1 or text.count(END) != 1:
        sys.exit("FAIL: Figure 1 markers not found exactly once in " + tex)
    block = text[text.index(BEGIN):text.index(END)]
    nodes = re.findall(r"\\node\[v\] \(([ab])(\d+)\) at \([-\d.]+,[-\d.]+\) \{(\d+)\};", block)
    edges = re.findall(r"\\draw\[([^]]*)\] \(([ab])(\d+)\) -- \(([ab])(\d+)\);", block)
    if len(nodes) + len(edges) != block.count(r"\node[v]") + block.count(r"\draw["):
        sys.exit("FAIL: unparsed node or edge lines in Figure 1")
    for side, v, label in nodes:
        if v != label:
            sys.exit("FAIL: node %s%s is labeled %s" % (side, v, label))
    drawn = {s: nx.Graph() for s in "ab"}
    for side, v, _ in nodes:
        drawn[side].add_node(int(v))
    style = {"a": {}, "b": {}}
    for st, s1, u, s2, v in edges:
        if s1 != s2:
            sys.exit("FAIL: an edge joins the two drawings")
        drawn[s1].add_edge(int(u), int(v)); style[s1][frozenset((int(u), int(v)))] = st
    for side, G, name in (("a", G1, "G1"), ("b", G2, "G2")):
        D = drawn[side]
        if set(D) != set(G) or {frozenset(e) for e in D.edges()} != {frozenset(e) for e in G.edges()}:
            sys.exit("FAIL: the %s drawing is not %s from data/graphs.g6" % (side, name))
    dashed = [e for e, s in style["a"].items() if "dashed" in s]
    thick_a = {e for e, s in style["a"].items() if "very thick" in s and "dashed" not in s}
    if dashed != [frozenset(DASHED)]:
        sys.exit("FAIL: the dashed edge of G1 is not {1,10}")
    H = G1.copy(); H.remove_edge(*DASHED)
    if not (nx.is_isomorphic(H, nx.from_graph6_bytes(b"J?bFF`wN?{?")) and H.number_of_edges() == 22):
        sys.exit("FAIL: G1 minus the dashed edge is not H")
    tri = {frozenset((a, b)) for a in TRIANGLE for b in TRIANGLE if a < b}
    if thick_a | {frozenset(DASHED)} != tri:
        sys.exit("FAIL: the thick edges of G1 with the dashed one are not the triangle {1,5,10}")
    thick_b = [tuple(e) for e, s in style["b"].items() if "very thick" in s]
    centers = set.intersection(*(set(e) for e in thick_b)) if len(thick_b) == 3 else set()
    if centers != {NEW} or G2.degree(NEW) != 3:
        sys.exit("FAIL: the thick edges of G2 are not the three edges at its degree-3 vertex %d" % NEW)
    y = next(iter(centers)); nbrs = list(G2[y])
    back = G2.copy(); back.remove_node(y); back.add_edges_from((a, b) for a in nbrs for b in nbrs if a < b)
    if not nx.is_isomorphic(back, G1) or not nx.is_isomorphic(delta_y(G1, TRIANGLE, max(G1) + 1), G2):
        sys.exit("FAIL: the Delta-Y transformation on {1,5,10} does not relate G1 and G2")
    print("Figure 1: the drawings are G1 and G2 from data/graphs.g6; the dashed edge {1,10} gives H; "
          "Delta-Y on the triangle {1,5,10} gives G2, with new vertex %d" % NEW)


if __name__ == "__main__":
    if sys.argv[1] == "--check":
        G1, G2 = graphs(sys.argv[2]); check(G1, G2, sys.argv[3])
    else:
        G1, G2 = graphs(sys.argv[1]); print(picture(G1, G2))
