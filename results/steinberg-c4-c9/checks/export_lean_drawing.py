#!/usr/bin/env python3
"""Reproduce Lean's untrusted drawing data from the published figure generator.

The rational witness is precisely the six-decimal drawing, not an unchecked
floating approximation. Lean separately proves its geometric properties.
--check compares the committed module, SVG and PDF with deterministic outputs.
"""
import argparse
from pathlib import Path
import draw_graph

ROOT = Path(__file__).resolve().parent.parent
OUTPUT = ROOT / 'lean/Steinberg/DrawingData.lean'


def render():
    adj, edges, rotation, faces = draw_graph.read_inputs()
    exact, _ = draw_graph.tutte(adj, faces)
    points = draw_graph.rounded(exact)
    # Existing independent orientation/closed-segment checker (not Lean's
    # separating-line checker) accepts this same exact finite-decimal drawing.
    draw_graph.check_geometry(points, edges, adj)
    draw_graph.check_rotation(points, rotation)
    for suffix, data in [('svg', draw_graph.svg(points, edges)),
                         ('pdf', draw_graph.pdf(points, edges))]:
        if (ROOT / f'data/graph.{suffix}').read_bytes() != data:
            raise ValueError(f'published graph.{suffix} differs from witness')
    lines = [
        '-- Generated by checks/export_lean_drawing.py; data are untrusted.',
        'import Steinberg.Data',
        'import Steinberg.Drawing',
        '', 'namespace Steinberg.Drawing', '',
        'set_option maxRecDepth 100000',
        'set_option maxHeartbeats 0', '',
        '/-- Exact millionths of a point used in the published SVG and PDF. -/',
        'def pointList : List IPoint := [']
    lines += [f'  ({points[v][0]}, {points[v][1]})' + (',' if v < len(points)-1 else '')
              for v in range(len(points))]
    lines += [']', '', 'def points (v : Nat) : IPoint := pointList[v]?.getD (0, 0)', '',
              'def drawingEdges : List (Nat × Nat) := [']
    ordered = sorted(edges)
    lines += [f'  ({u}, {v})' + (',' if i < len(ordered)-1 else '')
              for i, (u, v) in enumerate(ordered)]
    lines += [']', '', '/-- This is the graph parsed from the unchanged edge file. -/',
              'theorem drawingEdges_eq : drawingEdges = edgeList := by decide +kernel',
              '', 'end Steinberg.Drawing', '']
    return '\n'.join(lines)


def check_controls():
    """Use the existing orientation checker, independently of Lean's normals."""
    square = {0: (0, 0), 1: (1000000, 0), 2: (1000000, 1000000),
              3: (0, 1000000)}
    draw_graph.check_geometry(square, {(0, 1), (1, 2), (2, 3), (0, 3)}, square)
    print('PASS: independent closed-segment checker accepts the solved square')
    adj, edges, _, faces = draw_graph.read_inputs()
    points = draw_graph.rounded(draw_graph.tutte(adj, faces)[0])
    crossing = points | {32: (400000000, 400000000)}
    midpoint = tuple((points[0][i] + points[1][i]) // 2 for i in range(2))
    assert all((points[0][i] + points[1][i]) % 2 == 0 for i in range(2))
    assert draw_graph.on_segment(points[0], points[1], midpoint)
    for name, corrupt in [('crossing', crossing),
                          ('nonincident midpoint', points | {32: midpoint}),
                          ('coincident vertices', points | {32: points[0]})]:
        try:
            draw_graph.check_geometry(corrupt, edges, adj)
        except draw_graph.Rejection as error:
            print(f'PASS: independent checker rejects {name}: {error}')
        else:
            raise ValueError(f'independent checker accepted {name} corruption')


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    source = render()
    if args.check:
        if OUTPUT.read_text() != source:
            raise SystemExit('REJECT: Lean drawing data differ from published drawing')
        print('PASS: Lean coordinates match the exact published 82-vertex, 136-segment drawing')
        check_controls()
    else:
        OUTPUT.write_text(source)
        print('Wrote lean/Steinberg/DrawingData.lean')


if __name__ == '__main__':
    main()
