"""Exact congruence check of the facet library's merged names.

Pure Python standard library (fractions, math).  Nothing from enum/ is used.

Every polytope is built with exact coordinates in the field
K = Q(sqrt2, sqrt3), an element being a 4-tuple of Fractions (a, b, c, d)
meaning a + b*sqrt2 + c*sqrt3 + d*sqrt6.  Wythoffian polytopes are the orbit
of the Wythoff point under the reflection group generated by the simple
roots; prisms and duoprisms are written down explicitly.

For an alias pair (P, Q) the check is:
  1. |V(P)| = |V(Q)|;
  2. a bijection pi: V(P) -> V(Q) is found numerically (floats, used only as
     a search heuristic);
  3. EXACTLY, |p_i - p_j|^2 = |pi(p_i) - pi(p_j)|^2 in K for all i < j.
A distance-preserving bijection between finite subsets of Euclidean space
extends to an isometry of the ambient space (the Gram matrix of the vectors
p_i - p_0 is determined by the squared distances), so 1-3 prove P and Q are
congruent: their vertex sets, hence their convex hulls, are congruent.
"""
from fractions import Fraction as Fr
import itertools, math, sys
R2, R3, R6 = (math.sqrt(2), math.sqrt(3), math.sqrt(6))
ZERO = (Fr(0),) * 4

def K(a=0, b=0, c=0, d=0):
    return (Fr(a), Fr(b), Fr(c), Fr(d))

def kadd(x, y):
    return tuple((p + q for p, q in zip(x, y)))

def ksub(x, y):
    return tuple((p - q for p, q in zip(x, y)))

def kscale(r, x):
    return tuple((r * p for p in x))

def kmul(x, y):
    a, b, c, d = x
    e, f, g, h = y
    return (a * e + 2 * b * f + 3 * c * g + 6 * d * h, a * f + b * e + 3 * c * h + 3 * d * g, a * g + c * e + 2 * b * h + 2 * d * f, a * h + d * e + b * g + c * f)

def kfloat(x):
    return float(x[0]) + float(x[1]) * R2 + float(x[2]) * R3 + float(x[3]) * R6

def dot(u, v):
    s = ZERO
    for x, y in zip(u, v):
        s = kadd(s, kmul(x, y))
    return s

def sqdist(u, v):
    d = [ksub(x, y) for x, y in zip(u, v)]
    return dot(d, d)

def rdot(u, v):
    return sum((x * y for x, y in zip(u, v)))

def solve_rational(G, rhs):
    """Solve G x = rhs, G a rational nonsingular matrix (Gauss-Jordan)."""
    n = len(G)
    M = [list(map(Fr, G[i])) + [Fr(rhs[i])] for i in range(n)]
    for c in range(n):
        p = next((r for r in range(c, n) if M[r][c] != 0))
        M[c], M[p] = (M[p], M[c])
        piv = M[c][c]
        M[c] = [v / piv for v in M[c]]
        for r in range(n):
            if r != c and M[r][c] != 0:
                f = M[r][c]
                M[r] = [a - f * b for a, b in zip(M[r], M[c])]
    return [M[i][n] for i in range(n)]

def e(i, n, v=1):
    return [Fr(v) if j == i else Fr(0) for j in range(n)]

def vec(*xs):
    return [Fr(x) for x in xs]
h = Fr(1, 2)
ROOTS = {'A4': [[Fr(1) if j == i else Fr(-1) if j == i + 1 else Fr(0) for j in range(5)] for i in range(4)], 'B4': [vec(1, -1, 0, 0), vec(0, 1, -1, 0), vec(0, 0, 1, -1), vec(0, 0, 0, 1)], 'D4': [vec(1, -1, 0, 0), vec(0, 1, -1, 0), vec(0, 0, 1, -1), vec(0, 0, 1, 1)], 'F4': [vec(0, 1, -1, 0), vec(0, 0, 1, -1), vec(0, 0, 0, 1), vec(h, -h, -h, -h)]}
DIAGRAM = {'A4': {(0, 1): 3, (1, 2): 3, (2, 3): 3}, 'B4': {(0, 1): 3, (1, 2): 3, (2, 3): 4}, 'D4': {(0, 1): 3, (1, 2): 3, (1, 3): 3}, 'F4': {(0, 1): 3, (1, 2): 4, (2, 3): 3}}

def check_diagram(g):
    """cos(pi/m_ij) = -a_i.a_j/(|a_i||a_j|), checked exactly via squares."""
    R = ROOTS[g]
    for i, j in itertools.combinations(range(4), 2):
        m = DIAGRAM[g].get((i, j), 2)
        c2 = {2: Fr(0), 3: Fr(1, 4), 4: Fr(1, 2)}[m]
        ip = rdot(R[i], R[j])
        if not (ip <= 0 and ip * ip == c2 * rdot(R[i], R[i]) * rdot(R[j], R[j])):
            raise AssertionError((g, i, j))

def norm_K(r2):
    """|a| for a rational a.a in {1, 2}, as an element of K."""
    return {Fr(1): K(1), Fr(2): K(0, 1)}[r2]

def wythoff(name):
    """A4abcd etc.: orbit of the point at distance 1/2 from ringed mirrors."""
    g, rings = (name[:2], [int(c) for c in name[2:]])
    if not (len(rings) == 4 and any(rings)):
        raise AssertionError()
    check_diagram(g)
    R = ROOTS[g]
    n = len(R[0])
    G = [[rdot(a, b) for b in R] for a in R]
    rhs = [kscale(Fr(rings[i], 2), norm_K(rdot(R[i], R[i]))) for i in range(4)]
    xs = [[ZERO] * 4 for _ in range(4)]
    for comp in range(4):
        sol = solve_rational(G, [r[comp] for r in rhs])
        for j in range(4):
            xs[j] = list(xs[j])
            xs[j][comp] = sol[j]
    xs = [tuple(x) for x in xs]
    v = tuple((ZERO for _ in range(n)))
    for j in range(4):
        v = tuple((kadd(v[k], kscale(R[j][k], xs[j])) for k in range(n)))
    for i in range(4):
        ip = ZERO
        for k in range(n):
            ip = kadd(ip, kscale(R[i][k], v[k]))
        if not ip == rhs[i]:
            raise AssertionError((name, i))
    seen = {v}
    todo = [v]
    while todo:
        x = todo.pop()
        for a in R:
            ip = ZERO
            for k in range(n):
                ip = kadd(ip, kscale(a[k], x[k]))
            f = kscale(Fr(-2) / rdot(a, a), ip)
            y = tuple((kadd(x[k], kscale(a[k], f)) for k in range(n)))
            if y not in seen:
                seen.add(y)
                todo.append(y)
    return sorted(seen)

def cube_vertices(d):
    return [tuple((K(s) for s in signs)) for signs in itertools.product((h, -h), repeat=d)]

def prism(base):
    return [p + (K(s),) for p in base for s in (h, -h)]

def octahedron():
    pts = []
    for i in range(3):
        for s in (1, -1):
            pts.append(tuple((K(0, Fr(s, 2)) if j == i else ZERO for j in range(3))))
    return pts

def antiprism3():
    up = [(K(0, 0, Fr(1, 3)), K(0)), (K(0, 0, Fr(-1, 6)), K(h)), (K(0, 0, Fr(-1, 6)), K(-h))]
    dn = [(K(0, 0, Fr(-1, 3)), K(0)), (K(0, 0, Fr(1, 6)), K(h)), (K(0, 0, Fr(1, 6)), K(-h))]
    return [p + (K(0, 0, 0, Fr(1, 6)),) for p in up] + [p + (K(0, 0, 0, Fr(-1, 6)),) for p in dn]

def polygon4():
    return [(K(a), K(b)) for a in (h, -h) for b in (h, -h)]

def build(name):
    if name[:2] in ROOTS and len(name) == 6:
        return wythoff(name)
    if name == 'pr-cube':
        return prism(cube_vertices(3))
    if name == 'pr-oct':
        return prism(octahedron())
    if name == 'antiprism-prism-3':
        return prism(antiprism3())
    if name == 'duoprism-4-4':
        return [p + q for p in polygon4() for q in polygon4()]
    raise KeyError(name)

def edge_check(name, pts):
    """Every point has a neighbour at exact distance 1 and none closer
    (unit edges; a sanity check of the construction, not used for the proof)."""
    one = K(1)
    for p in pts[:min(len(pts), 8)]:
        ds = [sqdist(p, q) for q in pts if q != p]
        fl = [kfloat(d) for d in ds]
        m = min(fl)
        if not (abs(m - 1) < 1e-09 and one in ds):
            raise AssertionError((name, m))

def fl(pts):
    return [[kfloat(x) for x in p] for p in pts]

def fdist(u, v):
    return math.sqrt(sum(((a - b) ** 2 for a, b in zip(u, v))))

def gram_schmidt_frame(F):
    """Greedy indices of affinely independent points (as many as possible)."""
    idx = [0]
    basis = []
    for i in range(1, len(F)):
        w = [a - b for a, b in zip(F[i], F[0])]
        for b in basis:
            c = sum((x * y for x, y in zip(w, b)))
            w = [x - c * y for x, y in zip(w, b)]
        nrm = math.sqrt(sum((x * x for x in w)))
        if nrm > 1e-06:
            basis.append([x / nrm for x in w])
            idx.append(i)
    return (idx, basis)

def coords_in(F, idx, basis):
    """Affine coordinates (over the frame's orthonormal basis) of every point."""
    o = F[idx[0]]
    return [[sum(((a - b) * c for a, b, c in zip(p, o, bv))) for bv in basis] for p in F]

def find_bijection(P, Q, tol=1e-07):
    """Numerically: a frame of P, every distance-matching frame of Q, and the
    induced isometry; returns pi as a list (pi[i] = index in Q) or None."""
    FP, FQ = (fl(P), fl(Q))
    n = len(FP)
    idxP, bP = gram_schmidt_frame(FP)
    idxQ, bQ = gram_schmidt_frame(FQ)
    if len(idxP) != len(idxQ):
        return None
    k = len(idxP)
    CP = coords_in(FP, idxP, bP)
    CQ = coords_in(FQ, idxQ, bQ)
    DP = [[fdist(FP[a], FP[b]) for b in idxP] for a in idxP]
    keyQ = {}
    for j, c in enumerate(CQ):
        keyQ.setdefault(tuple((round(x, 5) for x in c)), []).append(j)

    def lookup(c):
        for key in itertools.product(*[(math.floor(x * 100000.0) / 100000.0, math.ceil(x * 100000.0) / 100000.0) for x in c]):
            for j in keyQ.get(tuple((round(x, 5) for x in key)), []):
                if max((abs(a - b) for a, b in zip(c, CQ[j]))) < tol * 100:
                    return j
        return None

    def extend(chosen):
        t = len(chosen)
        if t == k:
            yield list(chosen)
            return
        for j in range(n):
            if j in chosen:
                continue
            if all((abs(fdist(FQ[j], FQ[chosen[s]]) - DP[t][s]) < tol for s in range(t))):
                chosen.append(j)
                yield from extend(chosen)
                chosen.pop()
    framevecs = [[a - b for a, b in zip(CP[i], CP[idxP[0]])] for i in idxP[1:]]
    m = k - 1
    for img in extend([]):
        imgvecs = [[a - b for a, b in zip(CQ[j], CQ[img[0]])] for j in img[1:]]
        A = [row[:] for row in framevecs]
        inv = [[1.0 if i == j else 0.0 for j in range(m)] for i in range(m)]
        for c in range(m):
            p = max(range(c, m), key=lambda r: abs(A[r][c]))
            A[c], A[p] = (A[p], A[c])
            inv[c], inv[p] = (inv[p], inv[c])
            pv = A[c][c]
            A[c] = [x / pv for x in A[c]]
            inv[c] = [x / pv for x in inv[c]]
            for r in range(m):
                if r != c:
                    f = A[r][c]
                    A[r] = [x - f * y for x, y in zip(A[r], A[c])]
                    inv[r] = [x - f * y for x, y in zip(inv[r], inv[c])]
        pi = []
        used = set()
        ok = True
        for i in range(n):
            x = [a - b for a, b in zip(CP[i], CP[idxP[0]])]
            coef = [sum((x[r] * inv[r][c] for r in range(m))) for c in range(m)]
            y = [CQ[img[0]][c] + sum((coef[r] * imgvecs[r][c] for r in range(m))) for c in range(m)]
            j = lookup(y)
            if j is None or j in used:
                ok = False
                break
            used.add(j)
            pi.append(j)
        if ok:
            return pi
    return None

def exact_congruent(P, Q, pi):
    """True iff |P_i - P_j|^2 == |Q_pi(i) - Q_pi(j)|^2 exactly for all i<j."""
    n = len(P)
    if sorted(pi) != list(range(n)):
        return (False, 0)
    pairs = 0
    for i in range(n):
        for j in range(i + 1, n):
            pairs += 1
            if sqdist(P[i], P[j]) != sqdist(Q[pi[i]], Q[pi[j]]):
                return (False, pairs)
    return (True, pairs)

def prove(a, b, P=None, Q=None):
    P = build(a) if P is None else P
    Q = build(b) if Q is None else Q
    if len(P) != len(Q):
        return (False, 'vertex counts %d != %d' % (len(P), len(Q)))
    pi = find_bijection(P, Q)
    if pi is None:
        return (False, 'no distance-preserving bijection found numerically (%d vertices)' % len(P))
    ok, pairs = exact_congruent(P, Q, pi)
    if not ok:
        return (False, 'exact squared distances differ (pair %d of the numeric bijection)' % pairs)
    return (True, '%d vertices, %d pairwise squared distances equal in Q(sqrt2,sqrt3)' % (len(P), pairs))

def kstr(x):
    terms = [str(c) + s for c, s in zip(x, ('', '*sqrt2', '*sqrt3', '*sqrt6')) if c != 0]
    return ' + '.join(terms) or '0'
