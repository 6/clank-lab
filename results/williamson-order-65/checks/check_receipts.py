"""check_receipts: accept or reject a set of replay receipts. Does not import the search.

Usage: python3 -I check_receipts.py n m datadir units.tsv outdir [--kmin-file F] [--write-kmin F] [--range lo hi]
datadir holds rows.bin and classes.tsv (regenerated by `rows`). The checker:
  * checks classes.tsv against rows.bin (contiguous offsets, strictly increasing masks
    within each class, each mask's rowsum and compressed vector equal to its class's);
  * computes, per class, the number of rows minimal in their kernel-multiplier orbit
    (u == 1 mod L, gcd(u, n) = 1), by its own bit-permutation code;
  * requires every unit of units.tsv to have exactly one receipt across the batch files,
    with the same classes, sizes equal to class counts (designated row: kernel-minimal
    count), store/probe pair counts equal to the products the pairing implies,
    survivors <= pairs, matches >= solutions, and production settings in every END line;
  * requires every SOLUTION line to be in a unit and lists them (witness_check.py checks them).
Prints totals; exit 0 iff all checks pass."""
import os, sys
from math import gcd
import numpy as np

PAIRS = [(0, 1, 2, 3), (0, 2, 1, 3), (0, 3, 1, 2)]
PROD_FLAGS = "pair=1 xor=1 kmin=1 keybits=64"


def fail(msg):
    print("REJECT:", msg)
    sys.exit(1)


def bitperm(masks, src):
    out = np.zeros_like(masks)
    for i, s in enumerate(src):
        out |= ((masks >> np.uint32(s)) & np.uint32(1)) << np.uint32(i)
    return out


def main():
    n, m = int(sys.argv[1]), int(sys.argv[2])
    dd, uf, od = sys.argv[3], sys.argv[4], sys.argv[5]
    opts = sys.argv[6:]
    H, L = (n - 1) // 2, n // m
    rows = np.fromfile(os.path.join(dd, "rows.bin"), dtype="<u4")
    cls = []
    for line in open(os.path.join(dd, "classes.tsv")):
        f = line.rstrip("\n").split("\t")
        cls.append((int(f[0]), int(f[2]), [int(v) for v in f[3].split(",")], int(f[4]), int(f[5])))
    off = 0
    for i, (cid, r, X, c, o) in enumerate(cls):
        if cid != i or o != off or c <= 0:
            fail("class table offsets at class %d" % i)
        off += c
    if off != len(rows):
        fail("class counts do not sum to rows.bin length")
    # per-mask rowsum and compressed vector, vectorized per class
    sign = lambda seg, i: 1 - 2 * ((seg >> np.uint32(i - 1)) & np.uint32(1)).astype(np.int64)
    for cid, r, X, c, o in cls:
        seg = rows[o:o + c]
        if c > 1 and not np.all(seg[1:] > seg[:-1]):
            fail("class %d masks not strictly increasing" % cid)
        pop = np.zeros(c, dtype=np.int64)
        for i in range(1, H + 1):
            pop += (seg >> np.uint32(i - 1)) & np.uint32(1)
        if not np.all(n - 4 * pop == r):
            fail("class %d rowsum" % cid)
        for j in range((L - 1) // 2 + 1):
            tot = np.zeros(c, dtype=np.int64)
            for t in range(m):
                idx = j + L * t
                p = min(idx, n - idx)
                tot += 1 if p == 0 else sign(seg, p)
            if not np.all(tot == X[j]):
                fail("class %d compressed entry %d" % (cid, j))
    # kernel-minimal counts
    kus = [u for u in range(2, n) if gcd(u, n) == 1 and u % L == 1]
    srcs = [[min((u * i) % n, n - (u * i) % n) - 1 for i in range(1, H + 1)] for u in kus]
    kfile = None
    if "--kmin-file" in opts:
        kfile = opts[opts.index("--kmin-file") + 1]
    if kfile:
        kmin = [int(l.split()[1]) for l in open(kfile)]
    else:
        kmin = []
        for cid, r, X, c, o in cls:
            seg = rows[o:o + c]
            ok = np.ones(c, dtype=bool)
            for src in srcs:
                ok &= bitperm(seg, src) >= seg
            kmin.append(int(ok.sum()))
    if "--write-kmin" in opts:
        with open(opts[opts.index("--write-kmin") + 1], "w") as f:
            for i, k in enumerate(kmin):
                f.write("%d\t%d\n" % (i, k))
    count = [c for _, _, _, c, _ in cls]
    units = []
    for i, line in enumerate(open(uf)):
        f = [int(v) for v in line.split()]
        if f[0] != i:
            fail("units.tsv ids")
        units.append(tuple(f[1:5]))
    lo, hi = 0, len(units)
    if "--range" in opts:  # rehearsal: check only units lo..hi-1
        k = opts.index("--range"); lo, hi = int(opts[k + 1]), int(opts[k + 2])
    seen = [False] * len(units)
    for u in list(range(0, lo)) + list(range(hi, len(units))):
        seen[u] = True
    tot = dict(pairs=0, surv=0, matches=0, sols=0, cpu=0.0, passes_gt1=0)
    nsol_lines = 0
    for fn in sorted(os.listdir(od)):
        path = os.path.join(od, fn)
        if fn == "solutions.tsv":
            for line in open(path):
                f = line.split()
                if f and (f[0] != "SOLUTION" or len(f) != 6 or not 0 <= int(f[1]) < len(units)):
                    fail("bad solution line %r" % line)
                nsol_lines += bool(f)
            continue
        if not (fn.startswith("batch_") and fn.endswith(".tsv")):
            continue  # .tmp files of interrupted batches carry no credit
        b0, b1 = (int(v) for v in fn[6:-4].split("_"))
        if b0 < lo or b1 > hi:
            fail("batch %s outside the checked range" % fn)
        got, end = [], None
        for line in open(path):
            f = line.rstrip("\n").split("\t")
            if f[0] == "U":
                got.append(f)
            elif f[0] == "END":
                end = f
            else:
                fail("unknown line in %s" % fn)
        if end is None or int(end[1]) != b0 or int(end[2]) != b1:
            fail("missing or wrong END in %s" % fn)
        if not end[5].startswith(PROD_FLAGS):
            fail("non-production settings in %s: %s" % (fn, end[5]))
        if sorted(int(f[1]) for f in got) != list(range(b0, b1)):
            fail("batch %s does not hold exactly units %d..%d" % (fn, b0, b1 - 1))
        for f in got:
            u = int(f[1]); c4 = tuple(int(v) for v in f[2:6])
            p, d = int(f[6]), int(f[7]); sz = [int(v) for v in f[8:12]]
            npass, ps, pp, ss, sp, mt, so = (int(v) for v in f[12:19])
            if seen[u]:
                fail("unit %d has two receipts" % u)
            seen[u] = True
            if c4 != units[u]:
                fail("unit %d classes differ from units.tsv" % u)
            if not (0 <= p < 3 and 0 <= d < 4 and npass >= 1):
                fail("unit %d pairing/designation/passes" % u)
            want = [count[c] for c in c4]; want[d] = kmin[c4[d]]
            if sz != want:
                fail("unit %d list sizes %s != %s" % (u, sz, want))
            q = PAIRS[p]
            pl, pr = sz[q[0]] * sz[q[1]], sz[q[2]] * sz[q[3]]
            st, pb = (pr, pl) if pr <= pl else (pl, pr)
            if (ps, pp) != (st, pb):
                fail("unit %d pair counts" % u)
            if not (0 <= ss <= ps and 0 <= sp <= pp and so <= mt):
                fail("unit %d survivor/match counts" % u)
            tot["pairs"] += ps + pp; tot["surv"] += ss + sp; tot["matches"] += mt; tot["sols"] += so
            tot["cpu"] += float(f[19]); tot["passes_gt1"] += npass > 1
    missing = seen.count(False)
    if missing:
        fail("%d of %d units have no receipt (first: %d)" % (missing, len(units), seen.index(False)))
    if nsol_lines != min(tot["sols"], 10 ** 9):
        fail("solution lines %d != receipt solutions %d" % (nsol_lines, tot["sols"]))
    print("ACCEPT n=%d m=%d range=%d..%d units=%d/%d pairs=%d survivors=%d matches=%d solutions=%d multipass_units=%d receipt_cpu_h=%.3f"
          % (n, m, lo, hi - 1, hi - lo, hi - lo, tot["pairs"], tot["surv"], tot["matches"], tot["sols"], tot["passes_gt1"], tot["cpu"] / 3600))


if __name__ == "__main__":
    main()
