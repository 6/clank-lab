#!/usr/bin/env python3
"""Checker A for a certificate such as data/q5670.json (pure Python; imports
nothing from the other checkers).

B = F_2^2 + F_3^3 + F_5^2 + F_7^2.  An affine map w -> T w + v of B is a
4-tuple of (T, v), one block per prime.  G is the group generated by the
nine translations by basis vectors and the linear maps a1, a2 read from the
certificate; so G = {w -> T w + v : T in <a1, a2>, v in B}.  c0 is the
affine map w -> P(w + g0).

The checker verifies that c0 normalises G (conjugates of the generators
have linear part in <a1, a2>), so G<c0> is a group in which the class of c0
equals its G-class C.  Then C with x * y = y x y^-1 is a conjugation
quandle: the quandle axioms hold and C is closed under *.  It computes C,
the cycle type of R_c0 on C, and the orbit of c0 under R_y for a few y in
C, and compares them with the certificate's claim.  It exits 0 only if the
order and profile match the claim, the quandle is connected and some cycle
length does not divide the longest (Hayashi's conjecture fails).

usage: check_class.py qprime.json [seed]
"""
import json, random, resource, sys, time
from collections import Counter

PR = (2, 3, 5, 7)
DIM = (2, 3, 2, 2)


def fail(why):
    print("REJECT:", why)
    sys.exit(1)


def mat(rows, p):
    return tuple(tuple(c % p for c in r) for r in rows)


def ident(d):
    return tuple(tuple(int(i == j) for j in range(d)) for i in range(d))


def mm(A, B, p):
    d = len(A)
    return tuple(tuple(sum(A[i][k] * B[k][j] for k in range(d)) % p for j in range(d))
                 for i in range(d))


def mv(A, v, p):
    d = len(A)
    return tuple(sum(A[i][k] * v[k] for k in range(d)) % p for i in range(d))


def minv(A, p):
    d = len(A)
    M = [list(A[i]) + [int(i == j) for j in range(d)] for i in range(d)]
    for c in range(d):
        r = next(r for r in range(c, d) if M[r][c] % p)
        M[c], M[r] = M[r], M[c]
        iv = pow(M[c][c], p - 2, p)
        M[c] = [(a * iv) % p for a in M[c]]
        for r in range(d):
            if r != c and M[r][c]:
                f = M[r][c]
                M[r] = [(a - f * b) % p for a, b in zip(M[r], M[c])]
    return tuple(tuple(M[i][d:]) for i in range(d))


def comp(x, y):
    """x o y: apply y, then x."""
    out = []
    for (T1, v1), (T2, v2), p in zip(x, y, PR):
        Tv = mv(T1, v2, p)
        out.append((mm(T1, T2, p), tuple((a + b) % p for a, b in zip(Tv, v1))))
    return tuple(out)


def inverse(x):
    out = []
    for (T, v), p in zip(x, PR):
        Ti = minv(T, p)
        out.append((Ti, tuple((-a) % p for a in mv(Ti, v, p))))
    return tuple(out)


def lin(blocks):
    return tuple((mat(B, p), (0,) * len(B)) for B, p in zip(blocks, PR))


def trans(vs):
    return tuple((ident(d), tuple(c % p for c in v)) for v, d, p in zip(vs, DIM, PR))


cert = json.load(open(sys.argv[1]))
assert tuple(cert["primes"]) == PR and tuple(cert["dims"]) == DIM
a1 = lin(cert["a1"]); a2 = lin(cert["a2"])
gens = [a1, a2]
for j, d in enumerate(DIM):
    for b in range(d):
        vs = [(0,) * dd for dd in DIM]
        vs[j] = tuple(int(i == b) for i in range(d))
        gens.append(trans(vs))
for s in gens:  # every generator must be invertible
    for (T, v), p in zip(s, PR):
        minv(T, p)
gens += [inverse(s) for s in gens]
P = lin(cert["P"])
g0 = trans(cert["g0"])
c0 = comp(P, g0)
CAP = 10 ** 5


def linpart(x):
    return tuple(T for T, v in x)


def linmul(S, T):
    return tuple(mm(A, B, p) for A, B, p in zip(S, T, PR))


Alin = {tuple(ident(d) for d in DIM)}
front = list(Alin)
while front:
    front = [y for y in {linmul(x, linpart(s)) for x in front for s in (a1, a2)} if y not in Alin]
    Alin.update(front)
c0i = inverse(c0)
for s in gens:
    if linpart(comp(c0, comp(s, c0i))) not in Alin:
        print("REJECT: c0 does not normalise G"); sys.exit(1)
print("linear parts of G: %d; c0 normalises G" % len(Alin))


def conj(y, x):
    return comp(y, comp(x, inverse(y)))


def orbit(start, acts):
    seen = {start}; front = [start]
    while front:
        if len(seen) > CAP:
            fail("orbit larger than %d" % CAP)
        nxt = []
        for x in front:
            for s in acts:
                z = conj(s, x)
                if z not in seen:
                    seen.add(z); nxt.append(z)
        front = nxt
    return seen


t0 = time.process_time()
C = orbit(c0, gens)
print("|Q'| = |G-class of c0| =", len(C))
Cl = sorted(C)
R = {x: conj(c0, x) for x in Cl}  # R_c0(x) = c0 x c0^-1
assert set(R.values()) == C
seen = set(); lens = Counter()
for x in Cl:
    if x in seen:
        continue
    L, y = 0, x
    while y not in seen:
        seen.add(y); y = R[y]; L += 1
    lens[L] += 1
prof = dict(sorted(lens.items()))
print("cycle type of R_c0 (length: number of cycles):", prof)
lmax = max(prof)
print("longest", lmax, "; lengths not dividing it:", [l for l in prof if lmax % l])
random.seed(int(sys.argv[2]) if len(sys.argv) > 2 else 2)
Y = random.sample(Cl, 6)
O = orbit(c0, Y)
print("orbit of c0 under R_y for 6 random y in Q':", len(O), "of", len(C),
      "-> connected" if O == C else "-> NOT shown connected")
claim = cert["claim"]
if len(C) != claim["order"]:
    fail("order %d, claimed %d" % (len(C), claim["order"]))
if {str(k): v for k, v in prof.items()} != claim["profile"]:
    fail("profile differs from the claim")
if O != C:
    fail("not shown connected")
if not [l for l in prof if lmax % l]:
    fail("every cycle length divides the longest: no counterexample")
print("ACCEPT: connected quandle of order %d, profile as claimed; Hayashi's conjecture fails" % len(C))
print("CPU %.1f s, peak %d MB" % (time.process_time() - t0,
      resource.getrusage(resource.RUSAGE_SELF).ru_maxrss // 1024))
