"""Rigorous local data of Wythoffian uniform polytopes (arb balls).

For a Coxeter diagram and ring pattern: mirror normals from the Cholesky
factor of the Gram matrix (arb), the seed vertex v0 with <v0, n_i> = 1/2
on ringed mirrors and 0 on the others (unit edges), and the neighbours of
v0 = the orbit of {sigma_i(v0) : i ringed} under the stabiliser of v0
(generated by the unringed reflections).  Returned: v0, neighbours,
circumradius.  Faces at v0 are identified combinatorially elsewhere; the
coordinates here are the certified values used in checks.
"""
from flint import arb, arb_mat, ctx
ctx.prec = 200

def gram(m):
    n = len(m)
    PI = arb.pi()
    return [[arb(1) if i == j else -(PI / m[i][j]).cos() for j in range(n)] for i in range(n)]

def cholesky(G):
    n = len(G)
    L = [[arb(0)] * n for _ in range(n)]
    for i in range(n):
        for j in range(i + 1):
            s = G[i][j] - sum((L[i][k] * L[j][k] for k in range(j)), arb(0))
            if i == j:
                if not s > 0:
                    raise AssertionError()
                L[i][j] = s.sqrt()
            else:
                L[i][j] = s / L[j][j]
    return L

def block_normals(components):
    """components: list of Coxeter matrices; returns list of normals (lists of arb) in R^n."""
    rows, dim, off = ([], sum((len(c) for c in components)), 0)
    for m in components:
        L = cholesky(gram(m))
        for r in L:
            v = [arb(0)] * dim
            for k, x in enumerate(r):
                v[off + k] = x
            rows.append(v)
        off += len(m)
    return rows

def dot(a, b):
    return sum((x * y for x, y in zip(a, b)), arb(0))

def reflect(v, n):
    c = 2 * dot(v, n)
    return [x - c * y for x, y in zip(v, n)]

def solve(N, b):
    """Solve N v = b (rows of N are normals) by Gaussian elimination in arb."""
    n = len(N)
    A = [list(N[i]) + [b[i]] for i in range(n)]
    for col in range(n):
        piv = max(range(col, n), key=lambda r: abs(float(A[r][col].mid())))
        A[col], A[piv] = (A[piv], A[col])
        for r in range(n):
            if r != col:
                f = A[r][col] / A[col][col]
                A[r] = [x - f * y for x, y in zip(A[r], A[col])]
    return [A[i][n] / A[i][i] for i in range(n)]

def key(v, digits=9):
    return tuple((round(float(x.mid()), digits) for x in v))

def local_data(components, rings):
    N = block_normals(components)
    b = [arb(1) / 2 if r else arb(0) for r in rings]
    v0 = solve(N, b)
    ringed = [N[i] for i, r in enumerate(rings) if r]
    unringed = [N[i] for i, r in enumerate(rings) if not r]
    seeds = [reflect(v0, n) for n in ringed]
    seen = {key(s): s for s in seeds}
    frontier = list(seeds)
    while frontier:
        nf = []
        for v in frontier:
            for n in unringed:
                w = reflect(v, n)
                k = key(w)
                if k not in seen:
                    seen[k] = w
                    nf.append(w)
        frontier = nf
    R = dot(v0, v0).sqrt()
    return (v0, list(seen.values()), R)
