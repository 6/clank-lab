"""Exact models of the vertex sets (referee gaps G-T and U1).

A *model* of a polytope built by geom.py describes its vertex list (same
indices, vertex 0 the base) by facts that hold exactly, by construction:

* gens: permutations of the vertices by maps that are exact symmetries of
  the true vertex set (a Wythoff vertex set is the orbit of its point under
  the reflection group, so every simple reflection is a symmetry; a snub is
  the orbit of its point under two rotations; a product is acted on by the
  symmetries of its factors; see the classes below).  Each permutation is
  read off by the separation lemma: the image of a vertex under an exact
  symmetry is a vertex, and an enclosure closer than 1/2 to the enclosure of
  vertex k identifies it as vertex k.
* stab_gens: those of them (or products of them) that fix vertex 0.
* seeds: vertices at exact distance 1 from vertex 0 (|x - r_i x| = 2<x, a_i>
  = 1 for a ringed node i of a Wythoff point; a polygon or antiprism edge by
  the choice of its radius and height; a snub edge by the certified
  equations of its point).
* dimbound(S): an upper bound, exact by construction, on the affine
  dimension of a set S of vertices through vertex 0 (a parabolic orbit
  W_I x lies in x + span(a_i, i in I), so it has dimension <= |I|; a
  rotation orbit lies in a plane perpendicular to the axis; a product set
  A x B has dimension dim A + dim B; k points span at most k - 1).

From these, Model.stab() (the closure of stab_gens), Model.nbrs() (the
stabiliser orbits of the seeds: vertices at exact distance 1) and
Model.elem_to(t) (an exact symmetry taking vertex 0 to t, composed along a
breadth-first tree of gens) are exact.

sadi and gap (subsets of the 600-cell) are modelled in exact arithmetic in
Q(sqrt 5) instead (Q5Model): their coordinates are in Q(sqrt 5), and every
equality is decided exactly there.
"""
import itertools
import os
from fractions import Fraction
from functools import lru_cache
import numpy as np
from mpmath import iv
import geom
from ivla import ZERO, ONE, HALF, dot, dist2, matvec, inverse, transpose, matmul, vmid

def perm(a):
    return np.asarray(a, dtype=np.int64)

def compose(g, h):
    """g after h: i -> g[h[i]]"""
    return g[h]

def inv_perm(g):
    r = np.empty_like(g)
    r[g] = np.arange(len(g))
    return r

def key(g):
    return g.tobytes()

def closure(gens, n, limit=200000):
    """the group generated by gens (list of perms), as a list of perms"""
    e = np.arange(n, dtype=np.int64)
    out = [e]
    seen = {key(e)}
    i = 0
    while i < len(out):
        for g in gens:
            h = compose(g, out[i])
            k = key(h)
            if k not in seen:
                seen.add(k)
                out.append(h)
                if not len(out) <= limit:
                    raise AssertionError('group too large')
        i += 1
    return out

def orbit(points, gens):
    S = set(points)
    fr = list(S)
    while fr:
        nf = []
        for p in fr:
            for g in gens:
                q = int(g[p])
                if q not in S:
                    S.add(q)
                    nf.append(q)
        fr = nf
    return S

class Finder:
    """identify an interval point that is known to be a vertex (separation
    lemma: an enclosure closer than 1/2 to vertex k's enclosure is vertex k)"""

    def __init__(self, V):
        self.V = V
        self.grid = {}
        for i, v in enumerate(V):
            self.grid.setdefault(self._c(vmid(v)), []).append(i)
        self.dim = len(V[0])

    @staticmethod
    def _c(m):
        return tuple((int(np.floor(x * 2)) for x in m))

    def find(self, y):
        c = self._c(vmid(y))
        for d in itertools.product((-1, 0, 1), repeat=self.dim):
            for i in self.grid.get(tuple((a + b for a, b in zip(c, d))), ()):
                dd = dist2(y, self.V[i])
                if dd.b < 0.25:
                    return i
        raise ArithmeticError('image of a vertex under an exact symmetry not identified')

def perm_of_matrix(M, V, finder=None):
    """permutation of the vertex set V by the interval matrix M, which
    encloses an exact symmetry of V"""
    if finder is None:
        finder = Finder(V)
    return perm([finder.find(matvec(M, v)) for v in V])

class Model:

    def __init__(self, n, dim, gens, stab_gens, seeds, why=''):
        self.n = n
        self.dim = dim
        self.gens = [perm(g) for g in gens]
        self.stab_gens = [perm(g) for g in stab_gens]
        for g in self.stab_gens:
            if not g[0] == 0:
                raise AssertionError()
        self.seeds = list(seeds)
        self.why = why
        self._stab = None
        self._tree = None

    def stab(self):
        if self._stab is None:
            self._stab = closure(self.stab_gens, self.n)
        return self._stab

    def nbrs(self):
        return orbit(self.seeds, self.stab())

    def dimbound(self, S):
        return min(len(S) - 1, self.dim)

    def elem_to(self, t):
        """an exact symmetry g (a product of gens) with g[0] = t"""
        if self._tree is None:
            parent = {0: None}
            fr = [0]
            while fr:
                nf = []
                for v in fr:
                    for gi, g in enumerate(self.gens):
                        w = int(g[v])
                        if w not in parent:
                            parent[w] = (v, gi)
                            nf.append(w)
                fr = nf
            if not len(parent) == self.n:
                raise AssertionError('generators not transitive')
            self._tree = parent
        path = []
        v = t
        while self._tree[v] is not None:
            u, gi = self._tree[v]
            path.append(gi)
            v = u
        h = np.arange(self.n, dtype=np.int64)
        for gi in reversed(path):
            h = compose(self.gens[gi], h)
        if not h[0] == t:
            raise AssertionError()
        return h

class SegModel(Model):
    """[-1/2, 1/2]: vertices 0, 1; the flip is exact; distance 1."""

    def __init__(self):
        super().__init__(2, 1, [[1, 0]], [], [1], 'segment')

class PolygonModel(Model):
    """geom.polygon(p): vertex k at angle 2 pi k / p, radius 1/(2 sin(pi/p)).
    The rotation by 2 pi / p (k -> k+1) and the reflection in the x-axis
    (k -> -k) are exact symmetries; |v_1 - v_0| = 2 rho sin(pi/p) = 1."""

    def __init__(self, p):
        rot = [(k + 1) % p for k in range(p)]
        ref = [-k % p for k in range(p)]
        super().__init__(p, 2, [rot, ref], [ref], [1], 'polygon %d' % p)

class AntiprismModel(Model):
    """geom.antiprism(n): vertex 2k = top k (angle 2 pi k/n, height h/2),
    2k+1 = bottom k (angle 2 pi k/n + pi/n, height -h/2).  Exact symmetries:
    rotation by 2 pi/n, the reflection y -> -y (top k -> top -k, bottom k ->
    bottom -k-1), the rotation by pi/n composed with z -> -z (top k ->
    bottom k -> top k+1).  Seeds: top 1 (2 rho sin(pi/n) = 1) and bottom 0
    (2 rho^2 (1 - cos(pi/n)) + h^2 = 1 by the definition of h).  The top and
    the bottom n-gon lie in the planes z = +-h/2 (dimension 2)."""

    def __init__(self, n):
        N = 2 * n
        rot = [0] * N
        ref = [0] * N
        rr = [0] * N
        for k in range(n):
            rot[2 * k] = 2 * ((k + 1) % n)
            rot[2 * k + 1] = 2 * ((k + 1) % n) + 1
            ref[2 * k] = 2 * (-k % n)
            ref[2 * k + 1] = 2 * ((-k - 1) % n) + 1
            rr[2 * k] = 2 * k + 1
            rr[2 * k + 1] = 2 * ((k + 1) % n)
        super().__init__(N, 3, [rot, ref, rr], [ref], [2, 1], 'antiprism %d' % n)
        self.tops = frozenset(range(0, N, 2))

    def dimbound(self, S):
        if S <= self.tops:
            return min(len(S) - 1, 2)
        return min(len(S) - 1, 3)

class SnubModel(Model):
    """geom.snub(d): the orbit of p under the rotations A = r0 r1 and
    B = r1 r2 (exact symmetries).  Seeds: A p, A^-1 p, B p, B^-1 p and
    C p = A B p (the Krawczyk-certified point has |p - Ap| = |p - Bp| =
    |p - Cp|, scaled to 1).  The orbits of p under <A> and <B> lie in planes
    perpendicular to the rotation axes (dimension 2)."""

    def __init__(self, d):
        V, (pa, pb) = geom.snub_perm(d)
        pa, pb = (perm(pa), perm(pb))
        n = len(V)
        ia, ib = (inv_perm(pa), inv_perm(pb))
        seeds = [int(pa[0]), int(ia[0]), int(pb[0]), int(ib[0]), int(pa[pb[0]])]
        super().__init__(n, 3, [pa, pb], [], seeds, 'snub %s' % d)
        self.planar = {frozenset(orbit([0], [pa])), frozenset(orbit([0], [pb]))}

    def dimbound(self, S):
        if S in self.planar:
            return min(len(S) - 1, 2)
        return min(len(S) - 1, 3)

class WythoffModel(Model):
    """geom.wythoff_perm(diag, rings): the orbit of x (<x, a_i> = 1/2 for a
    ringed node, 0 otherwise) under the reflection group W.  gens: the simple
    reflections, plus the extra symmetries below; stab_gens: the reflections
    of unringed nodes (r_k x = x - 2<x, a_k> a_k = x) and the extra ones;
    seeds: r_i x for ringed i.  Flat sets: u(W_I x) for u in the stabiliser
    and I a set of nodes (dimension <= |I|).

    Extra symmetries (each fixes x and normalises the reflection group, so
    it maps the orbit onto itself; it maps unit roots to unit roots with the
    same Gram matrix, so it is an isometry):
    * palindromic rings of a diagram with a symmetric Coxeter matrix (A3,
      A4, F4 with unit roots): the diagram flip a_i -> a_{n-1-i};
    * B4 with node 3 unringed and rings[0] = rings[2]: the orbit is the
      W(D4)-orbit of x, D4 with simple roots a0, a1, a2, a2' = r3(a2)
      (centre a1), and the triality a0 -> a2 -> a2' -> a0, a1 -> a1 fixes x
      (<x, a2'> = <r3 x, a2> = <x, a2> = <x, a0>)."""

    def __init__(self, diag, rings, extras=True):
        rings = tuple(rings)
        V, perms = geom.wythoff_perm(diag, rings)
        n = len(V)
        r = len(rings)
        gens = [perm(p) for p in perms]
        stab_gens = [gens[k] for k in range(r) if not rings[k]]
        seeds = [int(gens[i][0]) for i in range(r) if rings[i]]
        self.V = V
        self.extra = []
        self.corrupt = os.environ.get('TCERT_CORRUPT', '')
        if extras and self.corrupt != 'drop-extra':
            al = geom.roots(diag)
            fin = None
            mats = []
            if diag in ('A3', 'A4', 'F4') and rings == rings[::-1]:
                src = al
                dst = [al[r - 1 - i] for i in range(r)]
                mats.append(('flip', src, dst))
            if diag == 'B4' and rings[3] == 0 and (rings[0] == rings[2]):
                a2p = geom.reflect(al[2], al[3])
                src = [al[0], al[1], al[2], a2p]
                dst = [al[2], al[1], a2p, al[0]]
                mats.append(('triality', src, dst))
            for nm, src, dst in mats:
                M = matmul(transpose(dst), inverse(transpose(src)))
                if fin is None:
                    fin = Finder(V)
                p = perm_of_matrix(M, V, fin)
                if not p[0] == 0:
                    raise AssertionError()
                gens.append(p)
                stab_gens.append(p)
                self.extra.append(nm)
        super().__init__(n, r, gens, stab_gens, seeds, 'wythoff %s %s' % (diag, rings))
        self.nodes = r
        self._flats = None

    def flats(self):
        if self.corrupt == 'drop-flats':
            return {}
        if self._flats is None:
            base = {}
            for k in range(self.nodes):
                for I in itertools.combinations(range(self.nodes), k):
                    O = frozenset(orbit([0], [self.gens[i] for i in I]))
                    base[O] = min(base.get(O, k), k)
            fl = {}
            for u in self.stab():
                for O, k in base.items():
                    S = frozenset((int(u[i]) for i in O))
                    fl[S] = min(fl.get(S, k), k)
            self._flats = fl
        return self._flats

    def dimbound(self, S):
        return min(len(S) - 1, self.dim, self.flats().get(S, self.dim))

class ProductModel(Model):
    """geom.product(X, Y): vertex i*|Y| + j = (x_i, y_j).  The symmetries of
    the factors act on their coordinates; for two equal factors (the same
    construction) the swap of the two coordinate blocks is a symmetry fixing
    the base.  Seeds (s, 0) and (0, s'); a product set A x B has dimension
    <= dim A + dim B."""

    def __init__(self, X, Y, swap=False):
        nX, nY = (X.n, Y.n)
        n = nX * nY
        idx = np.arange(n, dtype=np.int64)
        I, J = (idx // nY, idx % nY)

        def liftX(g):
            return g[I] * nY + J

        def liftY(g):
            return I * nY + g[J]
        gens = [liftX(g) for g in X.gens] + [liftY(g) for g in Y.gens]
        stab_gens = [liftX(g) for g in X.stab_gens] + [liftY(g) for g in Y.stab_gens]
        if swap:
            if not nX == nY:
                raise AssertionError()
            sw = J * nY + I
            gens.append(sw)
            stab_gens.append(sw)
        seeds = [s * nY for s in X.seeds] + [s for s in Y.seeds]
        super().__init__(n, X.dim + Y.dim, gens, stab_gens, seeds, 'product (%s) x (%s)' % (X.why, Y.why))
        self.X, self.Y = (X, Y)

    def dimbound(self, S):
        nY = self.Y.n
        A = frozenset((i // nY for i in S))
        B = frozenset((i % nY for i in S))
        if len(A) * len(B) == len(S) and 0 in A and (0 in B):
            return min(len(S) - 1, self.X.dimbound(A) + self.Y.dimbound(B))
        return min(len(S) - 1, self.dim)

def q(a, b=0):
    return (Fraction(a), Fraction(b))

def qadd(x, y):
    return (x[0] + y[0], x[1] + y[1])

def qsub(x, y):
    return (x[0] - y[0], x[1] - y[1])

def qmul(x, y):
    return (x[0] * y[0] + 5 * x[1] * y[1], x[0] * y[1] + x[1] * y[0])

def qinv(x):
    d = x[0] * x[0] - 5 * x[1] * x[1]
    if not d != 0:
        raise AssertionError()
    return (x[0] / d, -x[1] / d)
QZERO = q(0)
QONE = q(1)

def qiszero(x):
    return x[0] == 0 and x[1] == 0

def qdot(u, v):
    s = QZERO
    for a, b in zip(u, v):
        s = qadd(s, qmul(a, b))
    return s

def qvsub(u, v):
    return tuple((qsub(a, b) for a, b in zip(u, v)))

def qiv(x):
    return iv.mpf(x[0].numerator) / x[0].denominator + iv.mpf(x[1].numerator) / x[1].denominator * iv.sqrt(5)

def qrank(vecs):
    rows = [list(v) for v in vecs]
    rank = 0
    ncol = len(rows[0]) if rows else 0
    for c in range(ncol):
        piv = next((r for r in range(rank, len(rows)) if not qiszero(rows[r][c])), None)
        if piv is None:
            continue
        rows[rank], rows[piv] = (rows[piv], rows[rank])
        ip = qinv(rows[rank][c])
        for r in range(len(rows)):
            if r != rank and (not qiszero(rows[r][c])):
                f = qmul(rows[r][c], ip)
                rows[r] = [qsub(a, qmul(f, b)) for a, b in zip(rows[r], rows[rank])]
        rank += 1
    return rank

def qinverse(A):
    n = len(A)
    M = [list(A[i]) + [QONE if i == j else QZERO for j in range(n)] for i in range(n)]
    for c in range(n):
        p = next((r for r in range(c, n) if not qiszero(M[r][c])))
        M[c], M[p] = (M[p], M[c])
        ip = qinv(M[c][c])
        M[c] = [qmul(x, ip) for x in M[c]]
        for r in range(n):
            if r != c and (not qiszero(M[r][c])):
                f = M[r][c]
                M[r] = [qsub(a, qmul(f, b)) for a, b in zip(M[r], M[c])]
    return [row[n:] for row in M]

def qmatvec(M, v):
    return tuple((qdot(row, v) for row in M))

@lru_cache(None)
def cell600_exact():
    """geom.cell600() in the same order, exactly: coordinates in Q(sqrt 5),
    scaled by phi (unit edges)."""
    phi = (Fraction(1, 2), Fraction(1, 2))
    V = []
    for i in range(4):
        for s in (-1, 1):
            v = [QZERO] * 4
            v[i] = q(s)
            V.append(v)
    for signs in itertools.product((-1, 1), repeat=4):
        V.append([q(Fraction(s, 2)) for s in signs])
    base = [(Fraction(1, 4), Fraction(1, 4)), q(Fraction(1, 2)), (Fraction(-1, 4), Fraction(1, 4)), QZERO]
    evens = [p for p in itertools.permutations(range(4)) if geom._parity(p) == 0]
    for p in evens:
        for signs in itertools.product((-1, 1), repeat=3):
            v = [QZERO] * 4
            for k in range(3):
                v[p[k]] = qmul(base[k], q(signs[k]))
            V.append(v)
    if not len(V) == 120:
        raise AssertionError()
    return [tuple((qmul(c, phi) for c in v)) for v in V]

@lru_cache(None)
def sadi_exact():
    return cell600_exact()[24:]

@lru_cache(None)
def gap_exact():
    V = cell600_exact()
    a = V[0]
    b = next((v for v in V if qdot(qvsub(a, v), qvsub(a, v)) == QONE))
    keep = []
    ring1 = ring2 = 0
    for v in V:
        G = [[qdot(x, y) for y in (a, b, v)] for x in (a, b, v)]
        inplane = qrank(G) < 3
        orth = qiszero(qdot(v, a)) and qiszero(qdot(v, b))
        if inplane:
            ring1 += 1
        elif orth:
            ring2 += 1
        else:
            keep.append(v)
    if not (ring1 == 10 and ring2 == 10 and (len(keep) == 100)):
        raise AssertionError()
    return keep

class Q5Model(Model):
    """sadi or gap in exact arithmetic: neighbours, flatness and symmetries
    decided exactly in Q(sqrt 5)."""

    def __init__(self, name, V):
        E = sadi_exact() if name == 'sadi' else gap_exact()
        if not len(E) == len(V):
            raise AssertionError()
        for e, v in zip(E, V):
            if not dist2([qiv(c) for c in e], v).b < 0.25:
                raise AssertionError()
        self.E = E
        self.index = {e: i for i, e in enumerate(E)}
        n = len(E)
        self.n = n
        self.dim = 4
        self._nb = {}
        b = E[0]
        nb = self.nbrs_of(0)
        for tr in itertools.combinations(nb, 3):
            A = [b] + [E[t] for t in tr]
            if qrank(A) == 4:
                break
        self.tr = tr
        At = [[A[c][r] for c in range(4)] for r in range(4)]
        self.Ainv = qinverse(At)
        self.G = [[qdot(qvsub(E[x], b), qvsub(E[y], b)) for y in tr] for x in tr]
        stab = list(self._syms(0, first=False))
        self.why = 'exact Q(sqrt 5) ' + name
        self.seeds = nb
        self.stab_gens = stab
        self._stab = [perm(s) for s in stab]
        self.gens = self._stab + [self.elem_to(t) for t in nb]
        self._tree = None

    def nbrs_of(self, t):
        if t not in self._nb:
            et = self.E[t]
            self._nb[t] = [j for j, e in enumerate(self.E) if qdot(qvsub(e, et), qvsub(e, et)) == QONE]
        return self._nb[t]

    def _syms(self, dst, first):
        E = self.E
        d = E[dst]
        for img in itertools.permutations(self.nbrs_of(dst), 3):
            H = [[qdot(qvsub(E[x], d), qvsub(E[y], d)) for y in img] for x in img]
            if H != self.G:
                continue
            Bc = [[([d] + [E[t] for t in img])[c][r] for c in range(4)] for r in range(4)]
            M = [[qdot(Bc[r], [self.Ainv[k][c] for k in range(4)]) for c in range(4)] for r in range(4)]
            p = []
            for v in E:
                j = self.index.get(qmatvec(M, v))
                if j is None:
                    break
                p.append(j)
            else:
                yield perm(p)
                if first:
                    return

    def nbrs(self):
        return set(self.nbrs_of(0))

    def stab(self):
        return self._stab

    def elem_to(self, t):
        if t == 0:
            return np.arange(self.n, dtype=np.int64)
        g = next(self._syms(t, first=True))
        return g

    def dimbound(self, S):
        b = self.E[0]
        return qrank([qvsub(self.E[i], b) for i in S if i != 0]) if len(S) > 1 else 0

@lru_cache(None)
def model3(label):
    """model of the polyhedron geom.polyhedron(label)"""
    srcs = geom.poly3_sources()
    if label in srcs:
        V, src = srcs[label]
        if src[0] == 'wythoff':
            return WythoffModel(src[1], src[2])
        return SnubModel(src[1])
    if label[0] == 'P':
        return ProductModel(PolygonModel(int(label[1:])), SegModel())
    if label[0] == 'A':
        return AntiprismModel(int(label[1:]))
    raise KeyError(label)

@lru_cache(None)
def model4(name):
    if name[:2] in ('A4', 'B4', 'D4', 'F4', 'H4') and len(name) == 6:
        return WythoffModel(name[:2], tuple((int(c) for c in name[2:])))
    if name.startswith('pr-'):
        return ProductModel(model3(name[3:]), SegModel())
    if name.startswith('antiprism-prism-'):
        return ProductModel(AntiprismModel(int(name.split('-')[-1])), SegModel())
    if name.startswith('duoprism-'):
        p, qq = (int(x) for x in name.split('-')[1:])
        return ProductModel(PolygonModel(p), PolygonModel(qq), swap=p == qq)
    if name in ('sadi', 'gap'):
        return Q5Model(name, geom.polytope4(name))
    raise KeyError(name)

@lru_cache(None)
def model5(name):
    """model of a listed known 5-polytope (for its exact neighbour count)"""
    if name[:2] in ('A5', 'B5', 'D5') and len(name) == 7:
        return WythoffModel(name[:2], tuple((int(c) for c in name[2:])), extras=False)
    if name.startswith('prism-'):
        return ProductModel(model4(name[6:]), SegModel())
    if name.startswith('{'):
        p = int(name[1:name.index('}')])
        X = name[name.index('x') + 1:]
        return ProductModel(PolygonModel(p), model3(X))
    raise KeyError(name)
